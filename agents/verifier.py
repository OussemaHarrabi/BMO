"""
Verifier Agent - Fact-checks and scores responses using Phi-3.5.

This implements dual-model verification where a different model (Phi-3.5)
verifies the answers generated by the reasoner (Qwen3-4B).
"""

import json
from typing import Optional, List, Dict, Any
from dataclasses import dataclass
import logging

from core.ollama_client import OllamaClient, ModelRole

logger = logging.getLogger(__name__)


VERIFIER_SYSTEM_PROMPT = """You are a fact-checker for a personal memory assistant.
Verify that answers are accurate and supported by source memories.

Verification checklist:
1. Are cited memory IDs valid? (exist in sources)
2. Does the answer accurately reflect source content?
3. Are there claims NOT supported by sources? (hallucinations)
4. Is the answer complete given available information?
5. Is confidence score appropriate?

Confidence scoring guide:
- 0.9-1.0: Perfect match, all claims supported, high relevance
- 0.7-0.9: Good match, minor gaps or indirect support
- 0.4-0.7: Partial match, some claims unsupported
- 0.0-0.4: Poor match, mostly unsupported or irrelevant

Respond in JSON format ONLY."""


@dataclass
class VerificationResult:
    """Result of response verification."""
    verified_answer: str
    confidence: float
    valid_sources: List[str]
    issues: List[str]
    reasoning: str
    latency_ms: int
    model: str


class Verifier:
    """Verifies and fact-checks generated responses."""
    
    def __init__(self, client: Optional[OllamaClient] = None):
        """Initialize verifier.
        
        Args:
            client: Optional OllamaClient instance. Creates one if not provided.
        """
        self.client = client or OllamaClient()
    
    async def verify(
        self,
        query: str,
        draft_answer: str,
        cited_sources: List[str],
        source_memories: List[Dict[str, Any]]
    ) -> VerificationResult:
        """Verify a draft answer against source memories.
        
        Args:
            query: Original user query.
            draft_answer: Answer from reasoner.
            cited_sources: List of cited memory IDs.
            source_memories: Full memory objects for verification.
            
        Returns:
            VerificationResult with verified answer and confidence.
        """
        # Build source contents lookup
        source_contents = self._build_source_contents(source_memories)
        available_ids = set(source_contents.keys())
        
        # Format sources for prompt
        formatted_sources = "\n".join([
            f"- {sid}: {content[:200]}..."
            for sid, content in source_contents.items()
        ])
        
        prompt = f"""Verify this response:

USER QUESTION: {query}

DRAFT ANSWER: {draft_answer}

CITED SOURCES: {cited_sources}

SOURCE CONTENTS:
{formatted_sources}

---
JSON verification result (include: answer, confidence, sources, reasoning, issues):"""
        
        try:
            result = await self.client.generate(
                role=ModelRole.VERIFIER,
                prompt=prompt,
                system_prompt=VERIFIER_SYSTEM_PROMPT,
                format_json=True,
                temperature=0.2,
                max_tokens=800
            )
            
            logger.debug(f"Verifier raw response: {result.content[:500]}...")
            
            return self._parse_result(
                result.content,
                draft_answer,
                cited_sources,
                available_ids,
                result.latency_ms,
                result.model
            )
            
        except Exception as e:
            logger.error(f"Verification failed: {e}")
            # Fallback: return draft answer with medium confidence
            return VerificationResult(
                verified_answer=draft_answer,
                confidence=0.5,
                valid_sources=cited_sources,
                issues=["Verification failed, using original answer"],
                reasoning="Verification error occurred",
                latency_ms=0,
                model="fallback"
            )
    
    def verify_sync(
        self,
        query: str,
        draft_answer: str,
        cited_sources: List[str],
        source_memories: List[Dict[str, Any]]
    ) -> VerificationResult:
        """Verify answer (synchronous version).
        
        Args:
            query: Original user query.
            draft_answer: Answer from reasoner.
            cited_sources: List of cited memory IDs.
            source_memories: Full memory objects for verification.
            
        Returns:
            VerificationResult with verified answer and confidence.
        """
        source_contents = self._build_source_contents(source_memories)
        available_ids = set(source_contents.keys())
        
        formatted_sources = "\n".join([
            f"- {sid}: {content[:200]}..."
            for sid, content in source_contents.items()
        ])
        
        prompt = f"""Verify this response:

USER QUESTION: {query}

DRAFT ANSWER: {draft_answer}

CITED SOURCES: {cited_sources}

SOURCE CONTENTS:
{formatted_sources}

---
JSON verification result (include: answer, confidence, sources, reasoning, issues):"""
        
        try:
            result = self.client.generate_sync(
                role=ModelRole.VERIFIER,
                prompt=prompt,
                system_prompt=VERIFIER_SYSTEM_PROMPT,
                format_json=True,
                temperature=0.2,
                max_tokens=800
            )
            
            logger.debug(f"Verifier sync raw response: {result.content[:500]}...")
            
            return self._parse_result(
                result.content,
                draft_answer,
                cited_sources,
                available_ids,
                result.latency_ms,
                result.model
            )
            
        except Exception as e:
            logger.error(f"Verification failed: {e}")
            return VerificationResult(
                verified_answer=draft_answer,
                confidence=0.5,
                valid_sources=cited_sources,
                issues=["Verification failed, using original answer"],
                reasoning="Verification error occurred",
                latency_ms=0,
                model="fallback"
            )
    
    def _build_source_contents(self, memories: List[Dict[str, Any]]) -> Dict[str, str]:
        """Build memory ID to content mapping.
        
        Args:
            memories: List of memory dicts.
            
        Returns:
            Dict mapping memory_id to content.
        """
        contents = {}
        for mem in memories:
            memory_id = mem.get("memory_id", "")
            content = mem.get("summary") or mem.get("raw_text") or mem.get("content") or ""
            if memory_id and content:
                contents[memory_id] = content
        return contents
    
    def _parse_result(
        self,
        json_str: str,
        draft_answer: str,
        cited_sources: List[str],
        available_ids: set,
        latency_ms: int,
        model: str
    ) -> VerificationResult:
        """Parse JSON response into VerificationResult.
        
        Args:
            json_str: JSON string from LLM.
            draft_answer: Original draft answer.
            cited_sources: Originally cited sources.
            available_ids: Set of available memory IDs.
            latency_ms: Response latency.
            model: Model used.
            
        Returns:
            VerificationResult object.
        """
        try:
            json_str = json_str.strip()
            
            # Handle markdown code blocks
            if "```json" in json_str:
                json_str = json_str.split("```json")[1].split("```")[0]
            elif "```" in json_str:
                json_str = json_str.split("```")[1].split("```")[0]
            
            data = json.loads(json_str)
            
            # Get verified answer (use draft if not provided or empty)
            verified_answer = data.get("answer") or draft_answer
            
            # Get confidence
            confidence = float(data.get("confidence", 0.5))
            confidence = max(0.0, min(1.0, confidence))  # Clamp to [0, 1]
            
            claimed_sources = data.get("sources", cited_sources)
            if isinstance(claimed_sources, list):
                claimed_sources = [str(s) if not isinstance(s, dict) else s.get("id", str(s)) for s in claimed_sources]
            valid_sources = [s for s in claimed_sources if isinstance(s, str) and s in available_ids]
            
            issues = data.get("issues", [])
            if not isinstance(issues, list):
                issues = [str(issues)] if issues else []
            
            cited_source_ids = set()
            for s in cited_sources:
                if isinstance(s, str):
                    cited_source_ids.add(s)
                elif isinstance(s, dict):
                    cited_source_ids.add(s.get("id", s.get("memory_id", str(s))))
            invalid_citations = cited_source_ids - available_ids
            if invalid_citations:
                issues.append(f"Invalid citations: {invalid_citations}")
                confidence = min(confidence, 0.6)  # Reduce confidence
            
            return VerificationResult(
                verified_answer=verified_answer,
                confidence=confidence,
                valid_sources=valid_sources,
                issues=issues,
                reasoning=data.get("reasoning", ""),
                latency_ms=latency_ms,
                model=model
            )
            
        except (json.JSONDecodeError, KeyError, ValueError) as e:
            logger.warning(f"Failed to parse verifier JSON: {e}")
            
            valid_sources = [s for s in cited_sources if isinstance(s, str) and s in available_ids]
            confidence = 0.6 if valid_sources else 0.3
            
            return VerificationResult(
                verified_answer=draft_answer,
                confidence=confidence,
                valid_sources=valid_sources,
                issues=["Could not parse verification result"],
                reasoning="Fallback validation used",
                latency_ms=latency_ms,
                model=model
            )
    
    def quick_validate(
        self,
        draft_answer: str,
        cited_sources: List[str],
        available_ids: set
    ) -> tuple[float, List[str]]:
        """Quick validation without LLM call.
        
        Args:
            draft_answer: Draft answer to validate.
            cited_sources: Cited source IDs.
            available_ids: Set of available memory IDs.
            
        Returns:
            Tuple of (confidence, issues).
        """
        issues = []
        confidence = 0.7
        
        # Check for empty answer
        if not draft_answer or len(draft_answer.strip()) < 10:
            issues.append("Answer is too short or empty")
            confidence = 0.2
            return confidence, issues
        
        # Check citations
        valid_citations = [s for s in cited_sources if s in available_ids]
        invalid_citations = set(cited_sources) - available_ids
        
        if invalid_citations:
            issues.append(f"Invalid citations: {list(invalid_citations)}")
            confidence -= 0.2
        
        if not valid_citations and cited_sources:
            issues.append("No valid citations found")
            confidence = 0.3
        elif not cited_sources:
            issues.append("No sources cited")
            confidence = min(confidence, 0.5)
        
        # Check for hedging language (lower confidence)
        hedging = ["might", "possibly", "perhaps", "i think", "maybe", "not sure"]
        if any(h in draft_answer.lower() for h in hedging):
            confidence = min(confidence, 0.6)
        
        return max(0.0, confidence), issues


async def verify_response(
    query: str,
    draft_answer: str,
    cited_sources: List[str],
    source_memories: List[Dict[str, Any]],
    client: Optional[OllamaClient] = None
) -> VerificationResult:
    """Convenience function to verify a response.
    
    Args:
        query: Original user query.
        draft_answer: Answer from reasoner.
        cited_sources: List of cited memory IDs.
        source_memories: Full memory objects.
        client: Optional OllamaClient instance.
        
    Returns:
        VerificationResult with verified answer and confidence.
    """
    verifier = Verifier(client)
    return await verifier.verify(query, draft_answer, cited_sources, source_memories)
